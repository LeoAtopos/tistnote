async page => {
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  await page.setViewportSize({width:1440,height:900});
  await page.clock.install();
  await page.evaluate(async()=>{
    const {newNote,uid}=await import('/src/model.ts');
    const note=newNote();note.title='进入编辑前的品单';note.description='原来的说明';
    note.entries=[{id:uid(),name:'一一',reason:'原来的理由'}];
    note.createdAt=note.updatedAt='2025-01-01T00:00:00Z';
    note.lastReviewedAt='2025-01-02T00:00:00Z';
    localStorage.setItem('tistnote-development-preview-v1',JSON.stringify({vault:{path:'取消编辑验证',notes:[{note,revision:uid(),group:'原分组'}],groups:['原分组','新分组'],trash:[],templates:[],warnings:[]},history:{}}));
  });
  await page.reload();
  await page.locator('.note-card').filter({has:page.getByRole('heading',{name:'进入编辑前的品单',exact:true})}).click();
  const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')));
  const initial=(await stored()).vault.notes[0];
  const edit=()=>page.getByRole('button',{name:'编辑',exact:true}).click();
  const cancel=()=>page.getByRole('button',{name:'取消编辑',exact:true}).click();
  const confirmation=page.getByRole('dialog',{name:'取消编辑',exact:true});
  const title=page.getByRole('textbox',{name:'笔记主题',exact:true});
  await edit();await cancel();
  await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
  check(await confirmation.count()===0,'Unchanged edit required confirmation');
  check(JSON.stringify((await stored()).vault.notes[0])===JSON.stringify(initial),'Unchanged cancellation wrote the note');
  await edit();
  await title.fill('准备放弃的更新');
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('准备放弃的理由');
  await page.getByRole('combobox',{name:'回顾周期',exact:true}).selectOption('12');
  await page.clock.fastForward(61_000);
  check((await stored()).vault.notes[0].note.title==='准备放弃的更新','Autosave fixture did not persist edits');
  await cancel();await confirmation.waitFor();
  await confirmation.getByText(/退出编辑将丢失本次更新/).waitFor();
  await page.screenshot({path:'output/playwright/cancel-edit-confirm-desktop.png'});
  await confirmation.getByRole('button',{name:'继续编辑',exact:true}).click();
  check(await title.inputValue()==='准备放弃的更新','Continue editing lost content');
  await page.getByRole('combobox',{name:'笔记所在分组',exact:true}).selectOption('新分组');
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes[0].group==='新分组');
  await cancel();await confirmation.waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/cancel-edit-confirm-narrow.png'});
  const audit=await confirmation.evaluate(el=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minFont:Math.min(...[...el.querySelectorAll('*')].filter(n=>n.getClientRects().length).map(n=>parseFloat(getComputedStyle(n).fontSize)))}));
  check(audit.minFont>=13&&audit.scrollWidth<=audit.width,'Cancel dialog layout/font rule failed');
  await confirmation.getByRole('button',{name:'放弃更新',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
  let current=(await stored()).vault.notes[0];
  check(JSON.stringify(current.note)===JSON.stringify(initial.note)&&current.group===initial.group,'Cancellation failed to restore autosaved content/settings/folder/timestamps');
  check(Object.values((await stored()).history).flat().every(v=>v.kind!=='edit'),'Cancellation created a submitted version');
  await page.clock.fastForward(61_000);
  current=(await stored()).vault.notes[0];
  check(current.note.title===initial.note.title,'Pending autosave wrote discarded content back');
  await edit();
  await title.fill('尚未自动保存');
  await cancel();await confirmation.waitFor();
  await confirmation.getByRole('button',{name:'放弃更新',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/cancel-edit-read-narrow.png'});
  check((await stored()).vault.notes[0].note.title===initial.note.title,'Unsaved changes could not be discarded');
  await edit();
  await title.fill('写入失败时保留');
  await page.clock.fastForward(1000);
  await cancel();await confirmation.waitFor();
  await page.evaluate(()=>{
    window.cancelSetItem=Storage.prototype.setItem;
    Storage.prototype.setItem=function(k,v){if(k==='tistnote-development-preview-v1')throw Error('测试：取消写入失败');return window.cancelSetItem.call(this,k,v);};
  });
  await confirmation.getByRole('button',{name:'放弃更新',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'取消写入失败'}).waitFor();
  check(await title.inputValue()==='写入失败时保留','Failed cancellation discarded editing state');
  await page.evaluate(()=>Storage.prototype.setItem=window.cancelSetItem);
  await cancel();await confirmation.waitFor();
  await confirmation.getByRole('button',{name:'放弃更新',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
  await page.reload();
  check((await stored()).vault.notes[0].note.title===initial.note.title,'Cancelled content did not survive reload');
  return {unchanged:'exits directly without writing',changed:'asks before discard; Continue preserves edits',autosave:'rolled back; pending saves cannot reapply',restored:'content, review period, folder and original timestamps',history:'no submitted version; automatic history retained',failure:'stays editing; retry succeeds',narrow:audit};
}
