async page => {
  const check = (ok, message) => { if (!ok) throw Error(message); };
  await page.setViewportSize({width:1440,height:900});
  await page.clock.install({time:new Date(2026,9,25,12)});
  await page.evaluate(async()=>{
    const {newNote,uid} = await import('/src/model.ts');
    const records = ['待回顾品单','刚更新品单','提前回顾品单','旧版品单'].map((title,i)=>{
      const note = newNote(); note.title=title;
      note.entries=[{id:uid(),name:'一一',reason:'重看后的感受。'}];
      note.createdAt=note.updatedAt=new Date(2026,0,25,12).toISOString();
      if(i===1) note.updatedAt=new Date().toISOString();
      if(i===2) note.lastReviewedAt=new Date(2026,9,24,12).toISOString();
      if(i===3) { delete note.reviewIntervalMonths; delete note.lastReviewedAt; }
      return {note,revision:uid(),group:''};
    });
    localStorage.setItem('tistnote-development-preview-v1',JSON.stringify({vault:{path:'回顾验证',notes:records,trash:[],templates:[],warnings:[],groups:[]},history:{}}));
  });
  await page.reload();
  const card = title => page.locator('.note-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  const readState = () => page.evaluate(()=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')));
  const record = async title => (await readState()).vault.notes.find(r=>r.note.title===title);
  const confirm = () => page.getByRole('button',{name:'回顾确认',exact:true}).click();
  await card('待回顾品单').waitFor();
  check(await page.getByRole('img',{name:'需要回顾',exact:true}).count()===2,'Due/legacy reminder count wrong');
  check(await card('刚更新品单').getByRole('img',{name:'需要回顾',exact:true}).count()===0,'Recent update did not reset reminder');
  check(await card('提前回顾品单').getByRole('img',{name:'需要回顾',exact:true}).count()===0,'Early review did not reset reminder');
  await card('待回顾品单').click();
  await page.getByLabel('回顾状态',{exact:true}).getByText(/尚未确认/).waitFor();
  await page.screenshot({path:'output/playwright/review-desktop.png'});
  const before = await record('待回顾品单');
  const beforeVersions = (await readState()).history[before.note.id]?.length ?? 0;
  await confirm();
  await page.getByRole('status').filter({hasText:'已回顾确认'}).waitFor();
  let after = await record('待回顾品单');
  check(!!after.note.lastReviewedAt && after.note.updatedAt===before.note.updatedAt,'Review changed content timestamp or failed');
  check((await readState()).history[before.note.id].length===beforeVersions+1,'Review did not create a history record');
  check((await readState()).history[before.note.id].at(-1).kind==='review','Review history kind is incorrect');
  check(await card('待回顾品单').getByRole('img',{name:'需要回顾',exact:true}).count()===0,'Review did not clear dot');
  await page.clock.fastForward(61_000);
  await confirm();
  await page.waitForFunction(old=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r=>r.note.title==='待回顾品单').note.lastReviewedAt!==old,after.note.lastReviewedAt);
  await page.getByRole('button',{name:'更多笔记操作',exact:true}).click();
  await page.locator('.editor').getByRole('button',{name:'历史',exact:true}).click();
  const history=page.getByRole('dialog',{name:'审美与偏好的变化',exact:true});
  await history.getByText('已回顾确认当前品单，内容未更新。',{exact:true}).waitFor();
  check(await history.locator('.version-card').filter({hasText:'回顾确认'}).count()===2,'Repeated confirmations were not kept in note history');
  await page.screenshot({path:'output/playwright/review-history-desktop.png'});
  await history.getByRole('button',{name:'关闭对话框',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  const cycle = page.getByRole('combobox',{name:'回顾周期',exact:true});
  check(await cycle.inputValue()==='3','Default cycle not 3 months');
  await cycle.selectOption('6');
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).waitFor();
  after=await record('待回顾品单');
  check(after.note.reviewIntervalMonths===6,'Custom cycle was not persisted');
  await page.reload();
  await card('待回顾品单').click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  check(await cycle.inputValue()==='6','Reload lost cycle');
  await page.setViewportSize({width:390,height:844});
  await cycle.scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/review-edit-narrow.png'});
  const audit = () => page.evaluate(()=>{
    const nodes=[...document.querySelectorAll('body *')].filter(el=>el.getClientRects().length&&!el.closest('dialog:not([open])')&&([...el.childNodes].some(n=>n.nodeType===3&&n.textContent.trim())||el.matches('input,textarea,select')));
    return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minFont:Math.min(...nodes.map(el=>parseFloat(getComputedStyle(el).fontSize)))};
  });
  const editing=await audit();
  check(editing.minFont>=18 && editing.scrollWidth<=editing.width,'Narrow editing layout failed');
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await page.getByRole('button',{name:'回顾确认',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/review-read-narrow.png'});
  const reading=await audit();
  check(reading.minFont>=18 && reading.scrollWidth<=reading.width,'Narrow reading layout failed');
  await page.getByRole('button',{name:'‹ 笔记',exact:true}).click();
  await page.screenshot({path:'output/playwright/review-list-narrow.png'});
  await card('旧版品单').click();
  const legacy=await record('旧版品单');
  await page.evaluate(()=>{
    window.reviewSetItem=Storage.prototype.setItem;
    Storage.prototype.setItem=function(k,v){if(k==='tistnote-development-preview-v1')throw Error('测试：回顾写入失败');return window.reviewSetItem.call(this,k,v);};
  });
  await confirm();
  await page.getByRole('alert').filter({hasText:'回顾写入失败'}).waitFor();
  check(!(await record('旧版品单')).note.lastReviewedAt,'Failed review changed stored time');
  await page.evaluate(()=>Storage.prototype.setItem=window.reviewSetItem);
  await confirm();
  await page.waitForFunction(()=>!!JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r=>r.note.title==='旧版品单').note.lastReviewedAt);
  check((await record('旧版品单')).note.updatedAt===legacy.note.updatedAt,'Review retry changed content time');
  await page.reload();
  check(await page.getByRole('img',{name:'需要回顾',exact:true}).count()===0,'Reload lost confirmations');
  await page.getByRole('navigation',{name:'主导航',exact:true}).getByRole('button',{name:'历史',exact:true}).click();
  check(await page.locator('.activity-kind.reviewed').count()===2,'Global history did not merge repeated daily confirmations by note');
  check(/回顾\s*2\s*篇次/.test(await page.locator('.activity-summary').innerText()),'Review count missing from global summary');
  await page.screenshot({path:'output/playwright/review-activity-narrow.png'});
  await page.getByRole('navigation',{name:'主导航',exact:true}).getByRole('button',{name:/^笔记/}).click();
  await page.clock.setSystemTime(new Date(2027,4,5,12));
  await page.clock.fastForward(61_000);
  await page.waitForFunction(()=>document.querySelectorAll('.file-tree .review-dot').length===4);
  return {dueDots:'legacy and overdue only',review:'clears dot; repeat/early confirmation supported',timestamps:'content time unchanged',cycle:'6 months survives reload',failure:'no false confirmation; retry succeeds',editing,reading};
}
