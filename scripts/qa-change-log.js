async page => {
  const check = (ok, message) => { if (!ok) throw Error(message); };
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'创建或打开本地资料库',exact:true}).click();
  await page.getByRole('button',{name:'写一份新笔记',exact:true}).click();
  await page.getByRole('textbox',{name:'笔记主题',exact:true}).fill('我的电影选择');
  await page.getByRole('button',{name:'添加一个选择',exact:true}).click();
  await page.getByRole('textbox',{name:'条目 1 名称',exact:true}).fill('一一');
  const state = () => page.evaluate(()=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')));
  const logs = async () => Object.values((await state()).history).flat().filter(v=>v.kind==='edit');
  const finish = () => page.getByRole('button',{name:'完成编辑',exact:true}).click();
  const dialog = page.getByRole('dialog',{name:'更新日志',exact:true});
  const field = () => dialog.getByRole('textbox',{name:'更新日志（可选）',exact:true});
  const submit = () => dialog.getByRole('button',{name:'提交更新',exact:true});
  await finish();
  await dialog.waitFor();
  check(await submit().isEnabled(),'Empty update log cannot submit');
  check(await dialog.getByText('写下这次修改了什么，或为什么改变想法。',{exact:true}).count()===0,'Removed helper text remains');
  await field().fill('  \n  ');
  check(await submit().isEnabled(),'Whitespace update log cannot submit');
  await field().fill('补充重看后的感受。\n重新考虑了排序。');
  await page.screenshot({path:'output/playwright/change-log-desktop.png'});
  await dialog.getByRole('button',{name:'继续编辑',exact:true}).click();
  check(await logs().then(v=>v.length)===0,'Cancel created a submitted version');
  check(await page.getByRole('textbox',{name:'笔记主题',exact:true}).isVisible(),'Cancel left editing');
  await finish();
  check(await field().inputValue()==='补充重看后的感受。\n重新考虑了排序。','Cancel discarded draft log');
  await submit().click();
  await dialog.waitFor({state:'hidden'});
  await page.getByRole('article',{name:'笔记内容',exact:true}).waitFor();
  let committed = await logs();
  check(committed.length===1 && committed[0].label.includes('\n') && committed[0].note.entries[0].name==='一一','Log is missing or attached to wrong content');
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('生活里的细节，越看越有新的理解。');
  await page.clock.install();
  await page.clock.fastForward(61_000);
  await finish();
  await field().fill('自动保存之后，补记修改理由。');
  await submit().click();
  await dialog.waitFor({state:'hidden'});
  check((await logs()).length===2,'Automatic version swallowed submitted change log');
  await page.clock.resume();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await finish();
  await field().fill('复核当前选择，没有调整内容。');
  await page.setViewportSize({width:390,height:844});
  const audit = await dialog.evaluate(el=>({width:document.documentElement.scrollWidth,viewport:innerWidth,minFont:Math.min(...[...el.querySelectorAll('*')].filter(n=>n.getClientRects().length).map(n=>parseFloat(getComputedStyle(n).fontSize)))}));
  check(audit.width<=audit.viewport && audit.minFont>=18,'Narrow modal/font rule failed');
  await page.screenshot({path:'output/playwright/change-log-narrow.png'});
  await page.evaluate(()=>{
    window.changeLogSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = function(k,v) {
      if(k==='tistnote-development-preview-v1' && Object.values(JSON.parse(v).history).flat().filter(h=>h.kind==='edit').length>2) throw Error('测试：日志写入失败');
      return window.changeLogSetItem.call(this,k,v);
    };
  });
  await submit().click();
  await dialog.getByRole('alert').filter({hasText:'日志写入失败'}).waitFor();
  check(await field().inputValue()==='复核当前选择，没有调整内容。','Failed submission lost draft log');
  check(await page.locator('.editor input').count()>0,'Failed submission left editing');
  check((await logs()).length===2,'Failed submission persisted a version');
  await page.evaluate(()=>Storage.prototype.setItem=window.changeLogSetItem);
  await submit().click();
  await dialog.waitFor({state:'hidden'});
  check((await logs()).length===3,'Retry duplicated or lost submitted version');
  await page.reload();
  await page.locator('.note-card').filter({has:page.getByRole('heading',{name:'我的电影选择',exact:true})}).click();
  await page.getByRole('button',{name:'更多笔记操作',exact:true}).click();
  await page.locator('.editor').getByRole('button',{name:'历史',exact:true}).click();
  const history = page.getByRole('dialog',{name:'审美与偏好的变化',exact:true});
  await history.getByRole('region',{name:'更新日志',exact:true}).getByText('复核当前选择，没有调整内容。',{exact:true}).waitFor();
  await history.locator('.version-card').filter({hasText:'补充重看后的感受。'}).click();
  check((await history.getByRole('region',{name:'更新日志',exact:true}).textContent()).includes('重新考虑了排序。'),'Historical multiline log missing after reload');
  await page.setViewportSize({width:1440,height:900});
  await page.screenshot({path:'output/playwright/change-log-history.png'});
  await history.getByRole('button',{name:'关闭对话框',exact:true}).click();
  for (const label of ['', '  \n  ']) {
    await page.getByRole('button',{name:'编辑',exact:true}).click();
    await finish();
    await field().fill(label);
    await submit().click();
    await dialog.waitFor({state:'hidden'});
    check((await logs()).at(-1).label==='', 'Blank update log was not saved as empty');
  }
  check((await logs()).length===5,'Blank update submissions did not create versions');
  await page.getByRole('button',{name:'更多笔记操作',exact:true}).click();
  await page.locator('.editor').getByRole('button',{name:'历史',exact:true}).click();
  await history.locator('.version-card').getByText('笔记更新',{exact:true}).first().waitFor();
  check(await history.getByRole('region',{name:'更新日志',exact:true}).count()===0,'Empty log displays an empty log section');
  await history.getByRole('button',{name:'关闭对话框',exact:true}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await finish();
  await field().fill('遇到外部修改时也要保留这份日志。');
  await page.evaluate(async()=>{
    const appModule = await (await fetch('/src/App.tsx')).text();
    const apiUrl = appModule.match(/import \* as api from "([^"]+)"/)[1];
    const {command} = await import(apiUrl);
    const vault = await command('list');
    const record = vault.notes[0];
    record.note.description = '外部编辑的新内容';
    await command('save',{note:record.note,expected:record.revision});
    window.dispatchEvent(new Event('focus'));
  });
  check(await field().inputValue()==='遇到外部修改时也要保留这份日志。','Focus refresh discarded pending log');
  await submit().click();
  await dialog.getByRole('alert').filter({hasText:'CONFLICT:'}).waitFor();
  check((await logs()).length===5 && (await state()).vault.notes[0].note.description==='外部编辑的新内容','Conflict overwrote content or created a commit');
  check(await field().inputValue()==='遇到外部修改时也要保留这份日志。','Conflict discarded pending log');
  return {submittedLogs:(await logs()).length,cancel:'keeps editing and draft',validation:'blank/whitespace submissions succeed',autosave:'log preserved',failure:'draft kept; retry creates one version',conflict:'blocked; external content and log draft preserved',reload:'logs retained',narrow:audit};
}
