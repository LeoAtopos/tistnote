async page => {
  if(!new URL(page.url()).searchParams.has('preview'))throw Error('Use isolated preview');
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  await page.evaluate(()=>localStorage.removeItem('tistnote-development-preview-v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:960});
  await page.getByRole('button',{name:'创建或打开本地资料库',exact:true}).click();
  const nav=page.getByRole('navigation',{name:'主导航',exact:true});
  const templates=()=>nav.getByRole('button',{name:'模板库',exact:true}).click();
  const card=title=>page.locator('.template-card').filter({has:page.getByRole('heading',{name:title,exact:true})});
  const percent=()=>nav.locator('.template-coverage-count').innerText();
  await templates();
  check(await percent()==='0%','Empty vault coverage should be zero');
  await card('我最喜欢的电影').getByRole('button',{name:'开始填写',exact:true}).click();
  await templates();
  check(await percent()==='0%' && await card('我最喜欢的电影').locator('.template-covered').count()===0,'Empty template note was counted');
  const noteCard=page.getByRole('tree',{name:'笔记文件树',exact:true}).locator('.tree-note').filter({has:page.getByRole('heading',{name:'我最喜欢的电影',exact:true})});
  await nav.getByRole('button',{name:/^笔记/}).click();
  await noteCard.click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('button',{name:'添加一个选择',exact:true}).click();
  await page.locator('.entry-body input').fill('花样年华');
  await templates();
  check(await percent()==='2.2%','Populated note coverage incorrect');
  check(await card('我最喜欢的电影').locator('.template-covered').innerText()==='有品','Badge missing');
  await page.getByRole('button',{name:'展开或收起搜索',exact:true}).click();
  await page.getByRole('textbox',{name:'搜索',exact:true}).fill('讨厌');
  check(await percent()==='2.2%' && (await page.locator('.template-coverage-summary').innerText()).includes('1 / 45'),'Filter changed global denominator');
  await page.getByRole('button',{name:'清除',exact:true}).click();
  await card('我最喜欢的电影').getByLabel('我最喜欢的电影的模板操作',{exact:true}).click();
  await card('我最喜欢的电影').getByRole('button',{name:'另写一份',exact:true}).click();
  await page.getByRole('button',{name:'添加一个选择',exact:true}).click();
  await page.locator('.entry-body input').fill('重复填写同一模板');
  await templates();
  check(await percent()==='2.2%','Duplicate template notes inflated coverage');
  await page.evaluate(async()=>{
    const {command}=await import('/src/api.ts');
    const {newNote,uid}=await import('/src/model.ts');
    const note={...newNote(),title:' 读不下去的书 ',entries:[{id:uid(),name:'某本书',reason:'不合偏好'}]};
    await command('save',{note,expected:null});
  });
  await page.reload(); await templates();
  check(await percent()==='4.4%' && await card('读不下去的书').locator('.template-covered').count()===1,'Legacy exact-title note was not matched');
  const audit=()=>page.evaluate(()=>{
    const nodes=[...document.querySelectorAll('body *')].filter(el=>el.getClientRects().length&&getComputedStyle(el).visibility!=='hidden'&&([...el.childNodes].some(n=>n.nodeType===3&&n.textContent.trim())||el.matches('input,textarea,select')));
    const nav=document.querySelector('nav');
    return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minFont:Math.min(...nodes.map(el=>parseFloat(getComputedStyle(el).fontSize))),navWidth:nav.clientWidth,navScrollWidth:nav.scrollWidth};
  });
  const audits=[];
  for(const [width,height] of [[1440,960],[1090,1244],[390,844]]){
    await page.setViewportSize({width,height});
    await page.getByRole('button',{name:'展开或收起搜索',exact:true}).click();
    await page.getByRole('textbox',{name:'搜索',exact:true}).fill('我最喜欢的电影');
    await page.getByRole('button',{name:'随机一品 ↗',exact:true}).click();
    check(await page.locator('.random-card .template-covered').innerText()==='有品','Random selection lost covered badge');
    await page.screenshot({path:`output/playwright/template-coverage-${width}.png`,fullPage:true});
    const result=await audit();
    check(result.minFont>=13&&result.scrollWidth<=width&&result.navScrollWidth<=result.navWidth,'Font or overflow regression: '+JSON.stringify(result));
    audits.push(result);
    await page.getByRole('button',{name:'清除',exact:true}).click();
    await page.getByRole('button',{name:'展开或收起搜索',exact:true}).click();
  }
  await page.setViewportSize({width:1440,height:960});
  await nav.getByRole('button',{name:/^笔记/}).click();
  await page.getByRole('treeitem').filter({has:page.getByRole('heading',{name:'我最喜欢的电影',exact:true})}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'笔记主题',exact:true}).fill('改名后的电影品记');
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'更新日志（可选）',exact:true}).fill('模板覆盖率验证');
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await templates();
  check(await percent()==='4.4%','Renaming broke source association');
  await nav.getByRole('button',{name:/^笔记/}).click();
  await page.getByRole('treeitem').filter({has:page.getByRole('heading',{name:'改名后的电影品记',exact:true})}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.locator('.entry-body input').fill('   ');
  await templates();
  check(await percent()==='4.4%','Other completed note should retain coverage');
  await nav.getByRole('button',{name:/^笔记/}).click();
  await page.getByRole('treeitem').filter({has:page.getByRole('heading',{name:'我最喜欢的电影（1）',exact:true})}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('button',{name:'更多笔记操作',exact:true}).click();
  await page.getByRole('button',{name:'移入回收站',exact:true}).click();
  await templates();
  check(await percent()==='2.2%' && await card('我最喜欢的电影').locator('.template-covered').count()===0,'Trash note still counts');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByRole('dialog',{name:'本地资料库',exact:true}).getByRole('button',{name:'回收站',exact:true}).click();
  await page.locator('.trash-list article').getByRole('button',{name:'恢复',exact:true}).click();
  await templates();
  check(await percent()==='4.4%','Restore did not restore coverage');
  await page.reload(); await templates();
  check(await percent()==='4.4%','Coverage lost on reload');
  return {initial:'0%',completed:'has badge and percentage',filter:'global denominator preserved',duplicate:'counted once',legacy:'exact trimmed title',rename:'source preserved',clearTrashRestore:'derived from active populated notes',reload:'retained',audits};
}
