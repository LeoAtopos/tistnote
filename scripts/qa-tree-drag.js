async page => {
  if (!new URL(page.url()).searchParams.has('preview')) throw Error('Use isolated preview');
  const check = (ok,message) => { if (!ok) throw Error(message); };
  await page.evaluate(() => localStorage.removeItem('tistnote-development-preview-v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:960});
  await page.getByRole('button',{name:'创建或打开本地资料库',exact:true}).click();
  await page.evaluate(async () => {
    const {command} = await import('/src/api.ts');
    const {newNote,uid} = await import('/src/model.ts');
    for (const name of ['电影/收藏/空子组','设计/收藏','空组']) await command('group_create',{name});
    for (const [title,group] of [['电影清单','电影/收藏'],['藏片','电影/收藏'],['设计作品','设计'],['随手记','']]) {
      const note = newNote(); note.title=title; note.tags=['测试'];
      note.entries=[{id:uid(),name:'保留的条目',reason:'原理由'}];
      await command('save',{note,expected:null,group});
    }
  });
  await page.reload();
  const tree = page.getByRole('tree',{name:'笔记文件树',exact:true});
  const folder = path => tree.getByRole('treeitem',{name:`分组 ${path}`,exact:true});
  const card = title => tree.locator('.tree-note').filter({has:page.getByRole('heading',{name:title,exact:true})});
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')));
  const waitGroup = (title,group) => page.waitForFunction(({title,group}) => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r=>r.note.title===title)?.group===group,{title,group});
  const beginDrag = async locator => {
    const box = await locator.boundingBox();
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
    await page.mouse.down();
    await page.mouse.move(box.x+box.width/2+12,box.y+box.height/2+12,{steps:6});
    await page.getByRole('region',{name:'根目录拖放区',exact:true}).waitFor();
  };
  const toRoot = async locator => {
    await beginDrag(locator);
    const target = await page.getByRole('region',{name:'根目录拖放区',exact:true}).boundingBox();
    await page.mouse.move(target.x+target.width/2,target.y+target.height/2,{steps:10});
    await page.mouse.up();
  };
  check(await page.getByRole('region',{name:'根目录拖放区',exact:true}).count()===0,'Idle root drop zone adds clutter');
  await card('电影清单').click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('拖拽前的编辑');
  await card('电影清单').dragTo(folder('设计'));
  await waitGroup('电影清单','设计');
  check(await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).inputValue()==='拖拽前的编辑','Drag discarded editor draft');
  check((await stored()).vault.notes.find(r=>r.note.title==='电影清单').note.entries[0].reason==='拖拽前的编辑','Draft not saved before moving');
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('移动后仍可保存');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r=>r.note.title==='电影清单').note.entries[0].reason==='移动后仍可保存');
  const currentId=(await stored()).vault.notes.find(r=>r.note.title==='电影清单').note.id;
  await folder('空组').click();
  await card('随手记').dragTo(folder('空组'));
  await waitGroup('随手记','空组');
  check(await page.getByRole('textbox',{name:'笔记主题',exact:true}).inputValue()==='电影清单','Moving unselected note switched editor');
  await toRoot(card('随手记'));
  await waitGroup('随手记','');
  await folder('电影').dragTo(folder('设计'));
  await folder('设计/电影/收藏/空子组').waitFor();
  await waitGroup('藏片','设计/电影/收藏');
  const beforeInvalid=JSON.stringify((await stored()).vault);
  await folder('设计/电影').dragTo(folder('设计/电影/收藏'));
  check(JSON.stringify((await stored()).vault)===beforeInvalid,'Cycle changed vault');
  await folder('设计/电影/收藏').dragTo(folder('设计'));
  await page.getByRole('alert').filter({hasText:'分组名称已存在'}).waitFor();
  check(JSON.stringify((await stored()).vault)===beforeInvalid,'Conflicting folders were merged');
  await toRoot(folder('设计/电影'));
  await folder('电影/收藏/空子组').waitFor();
  await waitGroup('藏片','电影/收藏');
  check((await stored()).vault.notes.find(r=>r.note.id===currentId).note.entries[0].reason==='移动后仍可保存','Folder move damaged unrelated note');
  check(await page.getByRole('region',{name:'根目录拖放区',exact:true}).count()===0,'Root drop zone did not clear');
  const beforeCancel=JSON.stringify((await stored()).vault);
  await beginDrag(card('藏片'));
  await page.keyboard.press('Escape');
  await page.mouse.up();
  check(await page.getByRole('region',{name:'根目录拖放区',exact:true}).count()===0,'Escape did not cancel drag');
  check(JSON.stringify((await stored()).vault)===beforeCancel,'Cancelled drag moved content');
  await beginDrag(card('藏片'));
  const target=await folder('空组').boundingBox();
  await page.mouse.move(target.x+target.width/2,target.y+target.height/2,{steps:10});
  await page.screenshot({path:'output/playwright/tree-drag-feedback.png',fullPage:true});
  check(await folder('空组').evaluate(el=>el.classList.contains('tree-drop-target')),'Drop target not highlighted');
  await page.mouse.up();
  await waitGroup('藏片','空组');
  await card('藏片').click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('移动整个文件夹前的编辑');
  await folder('空组').dragTo(folder('设计'));
  await waitGroup('藏片','设计/空组');
  check(await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).inputValue()==='移动整个文件夹前的编辑','Folder move lost active draft');
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('文件夹移动后继续保存');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r=>r.note.title==='藏片').note.entries[0].reason==='文件夹移动后继续保存');
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'更新日志（可选）',exact:true}).fill('拖拽验证');
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await page.screenshot({path:'output/playwright/tree-drag-desktop.png',fullPage:true});
  const audit=()=>page.evaluate(()=>{
    const nodes=[...document.querySelectorAll('body *')].filter(el=>el.getClientRects().length&&getComputedStyle(el).visibility!=='hidden'&&([...el.childNodes].some(n=>n.nodeType===3&&n.textContent.trim())||el.matches('input,textarea,select')));
    return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minFont:Math.min(...nodes.map(el=>parseFloat(getComputedStyle(el).fontSize)))};
  });
  const desktop=await audit();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:/^笔记/}).first().click();
  await page.screenshot({path:'output/playwright/tree-drag-narrow.png',fullPage:true});
  const narrow=await audit();
  check(desktop.minFont>=13&&narrow.minFont>=13&&desktop.scrollWidth<=desktop.width&&narrow.scrollWidth<=narrow.width,'Font/overflow regression');
  const beforeReload=JSON.stringify((await stored()).vault);
  await page.reload();
  check(JSON.stringify((await stored()).vault)===beforeReload,'Moved groups lost on reload');
  return {note:'folder and root; current and unselected',folder:'nested contents and empty descendants; root return',guards:'cycles, same-name, cancel',draft:'saved before move; editing remains usable',reload:'persisted',desktop,narrow};
}
