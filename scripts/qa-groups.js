async (page) => {
  const check = (ok, message) => { if (!ok) throw Error(message); };
  const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')));
  const groupChanged = (id, group) => page.waitForFunction(({id, group}) => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes.find(r => r.note.id === id)?.group === group, {id, group});
  await page.setViewportSize({width: 1440, height: 960});
  await page.getByRole('button', {name:'创建或打开本地资料库',exact:true}).click();
  const title = page.getByRole('textbox', {name:'笔记主题',exact:true});
  const saved = () => page.locator('.save-state').filter({hasText:/^已保存$/}).waitFor();
  const manager = page.getByRole('dialog', {name:'管理分组',exact:true});
  const openGroups = async () => {
    await page.getByRole('button', {name:'笔记列表选项',exact:true}).click();
    await page.getByRole('button', {name:'管理分组',exact:true}).click();
  };
  const closeGroups = () => manager.getByRole('button', {name:'关闭对话框',exact:true}).click();
  const chooseFolder = async path => {
    const node = page.getByRole('treeitem', {name:`分组 ${path}`, exact:true});
    await node.click();
    if (await node.getAttribute('aria-expanded') === 'false') await node.click();
  };
  const createGroup = async name => {
    await manager.getByRole('textbox', {name:'新分组名称',exact:true}).fill(name);
    await manager.getByRole('button', {name:'新建分组',exact:true}).click();
    await page.waitForFunction(name => JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.groups.includes(name), name);
  };
  await page.getByRole('button', {name:'新建笔记',exact:true}).click();
  await title.fill('分组测试·全局唯一');
  await saved();
  const original = (await stored()).vault.notes[0];
  await openGroups();
  await createGroup('电影/收藏');
  await createGroup('设计');
  await page.screenshot({path:'output/playwright/groups-manager-desktop.png',fullPage:true});
  await manager.getByRole('textbox', {name:'新分组名称',exact:true}).fill('../越界');
  await manager.getByRole('button', {name:'新建分组',exact:true}).click();
  await manager.getByRole('alert').filter({hasText:'非法字符'}).waitFor();
  await manager.getByRole('textbox', {name:'新分组名称',exact:true}).fill('电影');
  await manager.getByRole('button', {name:'新建分组',exact:true}).click();
  await manager.getByRole('alert').filter({hasText:'名称已存在'}).waitFor();
  await closeGroups();
  await page.getByRole('combobox', {name:'笔记所在分组',exact:true}).selectOption('电影/收藏');
  await groupChanged(original.note.id, '电影/收藏');
  const moved = (await stored()).vault.notes.find(r => r.note.id === original.note.id);
  check(moved.revision === original.revision, 'Move changed the content revision');
  check(JSON.stringify(moved.note) === JSON.stringify(original.note), 'Move changed note content');

  await chooseFolder('设计');
  await page.getByRole('button', {name:'新建笔记',exact:true}).click();
  const second = (await stored()).vault.notes.find(r => r.note.id !== original.note.id);
  check(second.group === '设计', 'New note ignored the selected group');
  await title.fill(original.note.title);
  const duplicate = page.getByRole('dialog', {name:'标题重复',exact:true});
  await duplicate.waitFor();
  check((await stored()).vault.notes.find(r => r.note.id === second.note.id).note.title === '未命名笔记', 'Cross-group duplicate reached storage');
  await duplicate.getByRole('button', {name:'知道了',exact:true}).click();
  await title.fill('分组测试·设计');
  await saved();
  await chooseFolder('电影');
  check(await page.getByRole('treeitem',{name:'分组 电影',exact:true}).locator('..').locator('.note-card').count() === 1, 'Parent group did not include its child notes');
  await openGroups();
  await manager.getByRole('button', {name:'重命名分组 电影',exact:true}).click();
  await manager.getByRole('textbox', {name:'分组新名称',exact:true}).fill('影视');
  await manager.getByRole('button', {name:'保存名称',exact:true}).click();
  await groupChanged(original.note.id, '影视/收藏');
  await manager.getByRole('button', {name:'删除分组 影视/收藏',exact:true}).click();
  await manager.getByRole('alert').filter({hasText:'分组不是空的'}).waitFor();
  await manager.getByRole('button', {name:'重命名分组 影视',exact:true}).click();
  await manager.getByRole('textbox', {name:'分组新名称',exact:true}).fill('设计');
  await manager.getByRole('button', {name:'保存名称',exact:true}).click();
  await manager.getByRole('alert').filter({hasText:'名称已存在'}).waitFor();
  await manager.getByRole('button', {name:'取消重命名',exact:true}).click();
  await createGroup('待删除');
  await manager.getByRole('button', {name:'删除分组 待删除',exact:true}).click();
  await page.waitForFunction(() => !JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.groups.includes('待删除'));
  await closeGroups();
  await chooseFolder('影视');
  await page.locator('.note-card').filter({has:page.getByRole('heading',{name:original.note.title,exact:true})}).click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('button', {name:'更多笔记操作',exact:true}).click();
  await page.getByRole('button', {name:'移入回收站',exact:true}).click();
  await openGroups();
  await manager.getByRole('button', {name:'删除分组 影视/收藏',exact:true}).click();
  await page.waitForFunction(() => !JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.groups.includes('影视/收藏'));
  await manager.getByRole('button', {name:'删除分组 影视',exact:true}).click();
  await page.waitForFunction(() => !JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.groups.includes('影视'));
  await closeGroups();
  await page.getByRole('button', {name:'设置',exact:true}).click();
  await page.getByRole('dialog',{name:'本地资料库',exact:true}).getByRole('button', {name:'回收站',exact:true}).click();
  await page.getByRole('button', {name:'恢复',exact:true}).click();
  await groupChanged(original.note.id, '');
  await page.getByRole('button', {name:/^笔记/}).first().click();
  await page.getByRole('button', {name:'笔记列表选项',exact:true}).click();
  await page.getByRole('button', {name:'选择根目录',exact:true}).click();
  check(await page.locator('[role="tree"] > li > .note-card').count() === 1, 'Root contains grouped notes');
  check(await page.locator('.note-card').count() === 2, 'File tree lost a note');

  await openGroups();
  const long = '这个分组名称比较长用于确认字体保持可读并且能够正常换行/子分组';
  await createGroup(long);
  await closeGroups();
  await page.screenshot({path:'output/playwright/groups-desktop.png',fullPage:true});
  const audit = () => page.evaluate(() => {
    const visible = el => el.getClientRects().length && getComputedStyle(el).visibility !== 'hidden' && !el.closest('dialog:not([open])');
    const nodes = [...document.querySelectorAll('body *')].filter(el => visible(el) && ([...el.childNodes].some(n => n.nodeType === 3 && n.textContent.trim()) || el.matches('input,textarea,select')));
    return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minimumFont:Math.min(...nodes.map(el => parseFloat(getComputedStyle(el).fontSize))),small:nodes.filter(el=>parseFloat(getComputedStyle(el).fontSize)<18).map(el=>el.textContent.slice(0,30))};
  });
  const desktop = await audit();
  check(!desktop.small.length && desktop.scrollWidth <= desktop.width, 'Desktop font or overflow failed: '+JSON.stringify(desktop));
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', {name:/^笔记/}).first().click();
  await page.screenshot({path:'output/playwright/groups-narrow.png',fullPage:true});
  const narrow = await audit();
  check(!narrow.small.length && narrow.scrollWidth <= narrow.width, 'Narrow list layout failed');
  await openGroups();
  await page.screenshot({path:'output/playwright/groups-manager-narrow.png',fullPage:true});
  const modal = await audit();
  check(!modal.small.length && modal.scrollWidth <= modal.width, 'Group modal layout failed: '+JSON.stringify(modal));
  await closeGroups();
  await page.reload();
  await page.getByRole('button', {name:/^笔记/}).first().click();
  check((await stored()).vault.groups.includes('设计'), 'Groups did not persist after reload');
  check((await stored()).vault.notes.length === 2, 'Notes did not persist after reload');
  return {create:'including subgroups',rename:'updates child locations',move:'preserves note and revision',uniqueTitles:'global across groups',delete:'empty only',trash:'missing group restores ungrouped',reload:'persisted',desktop,narrow,modal};
}
