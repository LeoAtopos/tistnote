async page => {
  if (!new URL(page.url()).searchParams.has('preview')) throw Error('Use isolated preview');
  const check=(ok,message)=>{if(!ok) throw Error(message);};
  await page.evaluate(()=>localStorage.removeItem('tistnote-development-preview-v1'));
  await page.reload();
  await page.setViewportSize({width:1440,height:960});
  await page.getByRole('button',{name:'创建或打开本地资料库',exact:true}).click();
  const nav=page.getByRole('navigation',{name:'主导航',exact:true});
  const history=()=>nav.getByRole('button',{name:'历史',exact:true}).click();
  await history();
  const view=page.getByRole('region',{name:'品记使用历史',exact:true});
  await view.waitFor();
  check(await nav.locator('button').count()===3 && await nav.locator('button').nth(1).getAttribute('aria-label')==='模板库','History is not below templates');
  check(await view.locator('.activity-cell').count()>=365,'Annual calendar missing days');
  check(await view.locator('.activity-record').count()===0,'Empty vault invented history');
  await page.screenshot({path:'output/playwright/activity-empty.png',fullPage:true});
  const fixture=await page.evaluate(async()=>{
    const {newNote,uid}=await import('/src/model.ts');
    const state=JSON.parse(localStorage.getItem('tistnote-development-preview-v1'));
    const year=new Date().getFullYear();
    const day=(month,date,hour=12,y=year)=>new Date(y,month-1,date,hour).toISOString();
    const today=new Date();
    const todayAt=hour=>new Date(year,today.getMonth(),today.getDate(),hour).toISOString();
    const add=(title,at,trash=false)=>{
      const note={...newNote(),title,createdAt:at,updatedAt:at,entries:[{id:uid(),name:'保留的选择',reason:'原理由'}]};
      const record={note,revision:uid(),group:''};
      state.vault[trash?'trash':'notes'].push(record);
      state.history[note.id]=[{id:uid(),at,kind:'initial',label:'',note:structuredClone(note)}];
      return record;
    };
    const edit=(record,at,reason,kind='auto')=>{
      record.note={...record.note,updatedAt:at,entries:record.note.entries.map(e=>({...e,reason}))};
      state.history[record.note.id].push({id:uid(),at,kind,label:'',note:structuredClone(record.note)});
    };
    const main=add('持续记录的品记',day(3,4,9));
    edit(main,day(6,1,9),'六月的记录');
    edit(main,day(6,1,10),'六月第二次修改');
    state.history[main.note.id].push({id:uid(),at:day(6,2,9),kind:'milestone',label:'内容不变',note:structuredClone(main.note)});
    edit(main,todayAt(9),'今天的修改');
    const fresh=add('今天新增的品记',todayAt(8));
    const removed=add('去年回收站中的品记',day(8,15,10,year-1),true);
    edit(removed,day(8,16,11,year-1),'去年修改');
    for(let i=2;i<=36;i++){
      const date=new Date(year,today.getMonth(),today.getDate()-i*5,12);
      if(date.getFullYear()===year) add(`日常品记 ${i}`,date.toISOString());
    }
    for(let i=0;i<8;i++) add(`一月整理 ${i+1}`,day(1,18,10));
    for(let i=0;i<5;i++) add(`六月整理 ${i+1}`,day(6,15,10));
    localStorage.setItem('tistnote-development-preview-v1',JSON.stringify(state));
    const key=date=>`${date.getFullYear()}-${String(date.getMonth()+1).padStart(2,'0')}-${String(date.getDate()).padStart(2,'0')}`;
    return {year,today:key(today),mainId:main.note.id,freshId:fresh.note.id};
  });
  await page.reload();
  await history();
  await view.waitFor();
  check(await view.locator('.activity-record').count()===2,'Today should show one creation and one changed note');
  check(await view.locator('.activity-level-4').count()>0,'Graph lacks high intensity activity');
  await view.locator(`[data-date="${fixture.year}-06-01"]`).click();
  check(await view.locator('.activity-record').filter({hasText:'持续记录的品记'}).count()===1,'Repeated same-day edits were not merged');
  await view.locator(`[data-date="${fixture.year}-06-02"]`).click();
  check(await view.locator('.activity-record').count()===0,'Unchanged milestone counted as edit');
  await view.getByLabel('查看历史日期',{exact:true}).fill(`${fixture.year}-01-02`);
  check(await view.locator('.activity-record').count()===0,'Empty day contains records');
  await view.getByLabel('历史年份',{exact:true}).selectOption(String(fixture.year-1));
  check(await view.locator('.activity-record').count()===1,'Previous year detail missing');
  check(await view.locator('.activity-record').first().isDisabled(),'Trash record should not open as active note');
  check((await view.locator('.activity-record').innerText()).includes('在回收站'),'Trash status missing');
  await view.getByLabel('历史年份',{exact:true}).selectOption(String(fixture.year));
  await view.getByLabel('查看历史日期',{exact:true}).fill(`${fixture.year}-06-15`);
  await view.locator(`[data-date="${fixture.year}-06-15"]`).focus();
  await page.keyboard.press('ArrowLeft');
  check(await view.getByLabel('查看历史日期',{exact:true}).inputValue()===`${fixture.year}-06-08`,'Keyboard weekly navigation failed');
  await view.getByLabel('查看历史日期',{exact:true}).fill(fixture.today);
  await page.screenshot({path:'output/playwright/activity-desktop.png',fullPage:true});
  const audit=()=>page.evaluate(()=>{
    const nodes=[...document.querySelectorAll('body *')].filter(el=>el.getClientRects().length&&getComputedStyle(el).visibility!=='hidden'&&([...el.childNodes].some(n=>n.nodeType===3&&n.textContent.trim())||el.matches('input,textarea,select')));
    return {width:innerWidth,scrollWidth:document.documentElement.scrollWidth,minFont:Math.min(...nodes.map(el=>parseFloat(getComputedStyle(el).fontSize))),graphScrollable:document.querySelector('.activity-scroll').scrollWidth>document.querySelector('.activity-scroll').clientWidth};
  });
  const desktop=await audit();
  await view.locator('.activity-record').filter({hasText:'今天新增的品记'}).click();
  await page.getByRole('article',{name:'笔记内容',exact:true}).waitFor();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('从历史打开后的修改');
  await history();
  await view.waitFor();
  check(await view.locator('.activity-record').count()===3,'Leaving edit for history did not save and count new modification');
  const before=await view.locator('.activity-summary').innerText();
  await view.getByRole('button',{name:'刷新历史',exact:true}).click();
  check(await view.locator('.activity-summary').innerText()===before,'Refresh inflated activity');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/activity-narrow.png',fullPage:true});
  const narrow=await audit();
  check(desktop.minFont>=13&&narrow.minFont>=13&&desktop.scrollWidth<=desktop.width&&narrow.scrollWidth<=narrow.width,'Font or page overflow regression: '+JSON.stringify({desktop,narrow}));
  check(narrow.graphScrollable,'Narrow chart should scroll within its own panel');
  await page.reload();
  await history();
  check((await view.locator('.activity-summary').innerText())===before,'History totals lost after reload');
  return {nav:'below templates',calendar:'full year, intensity, empty/future days',detail:'date selection, daily merged edits, unchanged milestone excluded, trash status',keyboard:'weekly navigation',open:'opens note; edits saved when returning',refresh:'does not inflate counts',reload:'persisted from local versions',desktop,narrow};
}
