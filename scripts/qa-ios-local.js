async page => {
 const base=page.url(),context=await page.context().browser().newContext({viewport:{width:390,height:844},hasTouch:true,userAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 CriOS/140.0 Mobile/15E148 Safari/604.1'});
 const tab=await context.newPage(),errors=[];tab.on('pageerror',error=>errors.push(String(error)));
 const check=(ok,message)=>{if(!ok)throw Error(message)};
 const files=()=>tab.evaluate(()=>new Promise((resolve,reject)=>{const open=indexedDB.open('tistnote-browser-libraries-v1',1);open.onerror=()=>reject(open.error);open.onsuccess=()=>{const db=open.result,tx=db.transaction(['files','settings','libraries']),rows=tx.objectStore('files').getAll(),active=tx.objectStore('settings').get('active'),libraries=tx.objectStore('libraries').getAll();tx.oncomplete=()=>{db.close();resolve({active:active.result,libraries:libraries.result,rows:rows.result.map(r=>({...r,data:r.data===null?null:Array.from(r.data)}))})};tx.onabort=()=>reject(tx.error)}}));
 const settings=async()=>{await tab.getByRole('button',{name:'设置',exact:true}).click();return tab.getByRole('dialog').filter({has:tab.getByRole('heading',{name:/^本地资料库/})})};
 const finish=async()=>{await tab.getByRole('button',{name:'完成编辑',exact:true}).click();const log=tab.getByRole('dialog',{name:'更新日志',exact:true});await log.getByRole('button',{name:'提交更新',exact:true}).click();await log.waitFor({state:'hidden'})};
 try{
  await tab.addInitScript(()=>{
   localStorage.setItem('tistnote-preferences-v1',JSON.stringify({language:'zh',theme:'light'}));
   localStorage.setItem('tistnote-introduction-seen-v1','1');
   localStorage.setItem('tistnote-browser-tip-dismissed-v1','1');
   Object.defineProperty(window,'showDirectoryPicker',{configurable:true,value:undefined});
  });
  await tab.goto(base);
  const banner=tab.locator('.preview-banner');
  await banner.getByText(/iOS\/iPadOS/).waitFor();
  check((await banner.innerText()).includes('无痕模式')&&(await banner.innerText()).includes('完整备份'),'Storage risks not explained');
  await tab.getByRole('button',{name:'创建或打开浏览器资料库',exact:true}).click();
  await tab.getByRole('button',{name:'写一份新笔记',exact:true}).click();
  await tab.getByRole('textbox',{name:'笔记主题',exact:true}).fill('爱憎都有的品单');
  await tab.getByRole('textbox',{name:'笔记主题',exact:true}).press('Enter');
  await tab.getByRole('textbox',{name:'主题说明',exact:true}).fill('浏览器里的真实本地资料库');
  await tab.getByRole('button',{name:'添加一个选择',exact:true}).click();
  await tab.getByRole('textbox',{name:'条目 1 名称',exact:true}).fill('喜欢大山，也记下不喜欢的地方');
  await tab.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('留下自己的判断');
  await finish();
  await tab.screenshot({path:'output/playwright/ios-local-warning-390.png'});
  await banner.getByRole('button',{name:'关闭提示',exact:true}).click();
  await tab.reload();
  await tab.getByRole('heading',{name:'爱憎都有的品单',exact:true}).last().waitFor();
  check(await banner.count()===0,'Tip dismissal was not remembered');
  const saved=await files(),noteFile=saved.rows.find(r=>r.library===saved.active&&r.path.endsWith('.md'));
  check(noteFile&&new TextDecoder().decode(new Uint8Array(noteFile.data)).includes('留下自己的判断'),'IndexedDB did not preserve Markdown');
  const second=await context.newPage();
  await second.goto(base);await second.getByRole('button',{name:'设置',exact:true}).waitFor();
  await second.getByRole('alert').filter({hasText:'请先关闭其他'}).waitFor();await second.close();
  await tab.getByRole('heading',{name:'爱憎都有的品单',exact:true}).last().click();
  await tab.getByRole('button',{name:'编辑',exact:true}).click();
  await tab.evaluate(()=>{const put=IDBObjectStore.prototype.put;IDBObjectStore.prototype.put=function(value,...args){if(this.name==='files'&&value?.path?.endsWith('.md')&&new TextDecoder().decode(value.data).includes('模拟空间不足')){IDBObjectStore.prototype.put=put;throw new DOMException('simulated','QuotaExceededError')}return put.call(this,value,...args)}});
  await tab.getByRole('textbox',{name:'条目 1 理由',exact:true}).fill('模拟空间不足');
  await tab.getByRole('alert').filter({hasText:'浏览器存储空间不足'}).waitFor();
  check(JSON.stringify((await files()).rows.find(r=>r.library===saved.active&&r.path===noteFile.path).data)===JSON.stringify(noteFile.data),'Failed write changed original note bytes');
  await tab.getByRole('button',{name:'取消编辑',exact:true}).click();
  await tab.getByRole('dialog',{name:'取消编辑',exact:true}).getByRole('button',{name:'放弃更新',exact:true}).click();
  await tab.getByRole('button',{name:'编辑',exact:true}).waitFor();
  let modal=await settings();
  check(await modal.getByRole('button',{name:'在文件管理器中打开',exact:true}).count()===0,'Folder-only action remained visible');
  await modal.getByText(/资料库保存在浏览器内部/).waitFor();
  const download=tab.waitForEvent('download');await modal.getByRole('button',{name:'完整备份',exact:true}).click();
  const backup=await download,backupPath=await backup.path();await backup.saveAs('output/playwright/ios-browser-library.zip');
  await tab.getByRole('status').filter({hasText:'已生成备份'}).waitFor();
  const chooser=tab.waitForEvent('filechooser');await modal.getByRole('button',{name:'从备份恢复',exact:true}).click();
  await(await chooser).setFiles(backupPath);
  await tab.getByRole('status').filter({hasText:'备份已恢复到新的浏览器资料库'}).waitFor();
  const restored=await files();check(restored.active!==saved.active&&restored.libraries.length===2,'Restore replaced the original library');
  check(JSON.stringify(restored.rows.find(r=>r.library===saved.active&&r.path===noteFile.path).data)===JSON.stringify(noteFile.data),'Restore modified original library');
  check(JSON.stringify(restored.rows.find(r=>r.library===restored.active&&r.path===noteFile.path).data)===JSON.stringify(noteFile.data),'Restore changed Markdown');
  modal=await settings();
  const invalid=tab.waitForEvent('filechooser');await modal.getByRole('button',{name:'从备份恢复',exact:true}).click();
  await(await invalid).setFiles({name:'broken.zip',mimeType:'application/zip',buffer:Buffer.from('broken')});
  await tab.getByRole('alert').filter({hasText:'备份格式无效'}).waitFor();
  check((await files()).active===restored.active&&(await files()).libraries.length===2,'Invalid restore changed active data');
  await modal.getByRole('button',{name:'创建 / 切换资料库',exact:true}).click();
  const chooserModal=tab.getByRole('dialog',{name:'浏览器资料库',exact:true});
  await chooserModal.getByRole('button',{name:'浏览器资料库',exact:true}).click();
  await chooserModal.waitFor({state:'hidden'});
  check((await files()).active===saved.active,'Switch did not reopen original library');
  modal=await settings();await modal.getByRole('button',{name:'创建 / 切换资料库',exact:true}).click();
  await chooserModal.getByRole('textbox',{name:'资料库名称',exact:true}).fill('另一份品记');
  await chooserModal.getByRole('button',{name:'新建资料库',exact:true}).click();
  await chooserModal.waitFor({state:'hidden'});
  await tab.getByRole('button',{name:'写一份新笔记',exact:true}).waitFor();
  check((await files()).libraries.length===3,'New browser library missing');
  modal=await settings();
  const markdownPicker=tab.waitForEvent('filechooser');await modal.getByRole('button',{name:'导入品记 Markdown',exact:true}).click();
  await(await markdownPicker).setFiles({name:'note.md',mimeType:'text/markdown',buffer:Buffer.from(noteFile.data)});
  await modal.waitFor({state:'hidden'});
  await tab.getByRole('heading',{name:'爱憎都有的品单',exact:true}).last().waitFor();
  const imported=await files(),importedNote=imported.rows.find(r=>r.library===imported.active&&r.path.endsWith('.md'));
  check(importedNote.path!==noteFile.path,'Markdown import did not assign a new note ID');
  await tab.setViewportSize({width:1024,height:768});
  await tab.evaluate(()=>{const key='tistnote-preferences-v1',newValue=JSON.stringify({language:'en',theme:'dark'});localStorage.setItem(key,newValue);window.dispatchEvent(new StorageEvent('storage',{key,newValue}));});
  await tab.getByRole('button',{name:'Settings',exact:true}).click();
  const english=tab.getByRole('dialog').filter({has:tab.getByRole('heading',{name:/^Local library/})});
  await english.getByText(/Avoid private browsing/).waitFor();
  await tab.screenshot({path:'output/playwright/ios-local-settings-en-ipad.png'});
  const minFont=await english.evaluate(el=>Math.min(...[...el.querySelectorAll('*')].filter(n=>n.getClientRects().length&&[...n.childNodes].some(c=>c.nodeType===3&&c.textContent.trim())).map(n=>parseFloat(getComputedStyle(n).fontSize))));
  check(minFont>=13,'Text below 13px');
  check(await tab.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Horizontal page overflow');
  check(errors.length===0,errors.join('\n'));
  return {browserLocal:true,markdown:true,reload:true,tipDismissal:true,multiTabLock:true,quotaPreservesOriginal:true,zipDownload:true,restoreNewLibrary:true,corruptBackupPreserves:true,switchLibrary:true,newLibrary:true,markdownImport:true,english:true,minFont};
 }catch(error){await tab.screenshot({path:'output/playwright/ios-local-failure.png'});throw Error(String(error)+'\n'+(await tab.locator('body').innerText()).slice(-2500))}
 finally{await context.close()}
}
