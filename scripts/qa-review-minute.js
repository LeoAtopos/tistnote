async page => {
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  await page.setViewportSize({width:1440,height:900});
  await page.clock.install({time:new Date(2026,9,25,12)});
  await page.clock.pauseAt(new Date(2026,9,25,12,0,1));
  await page.getByRole('button',{name:'创建或打开本地资料库',exact:true}).click();
  await page.getByRole('button',{name:'写一份新笔记',exact:true}).click();
  await page.getByRole('textbox',{name:'笔记主题',exact:true}).fill('一分钟回顾验证');
  const cycle=page.getByRole('combobox',{name:'回顾周期',exact:true});
  await cycle.selectOption('test-minute');
  await page.setViewportSize({width:390,height:844});
  await cycle.scrollIntoViewIfNeeded();
  await page.screenshot({path:'output/playwright/review-minute-setting.png'});
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await page.getByRole('button',{name:'回顾确认',exact:true}).waitFor();
  const record=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('tistnote-development-preview-v1')).vault.notes[0]);
  check((await record()).note.reviewTestMinute===true,'Test cycle was not saved');
  await page.reload();
  const card=page.locator('.note-card').filter({has:page.getByRole('heading',{name:'一分钟回顾验证',exact:true})});
  check(await card.locator('.review-dot').count()===0,'Reminder appears before one minute');
  await page.clock.runFor(59_000);
  check(await card.locator('.review-dot').count()===0,'Reminder appears too early');
  await page.clock.runFor(2_000);
  await card.locator('.review-dot').waitFor();
  await page.screenshot({path:'output/playwright/review-minute-due.png'});
  await card.click();
  await page.getByRole('button',{name:'回顾确认',exact:true}).click();
  const reviewed=await record();
  check(!!reviewed.note.lastReviewedAt,'Minute review did not confirm');
  await page.getByRole('button',{name:'‹ 笔记',exact:true}).click();
  check(await card.locator('.review-dot').count()===0,'Confirm did not clear reminder');
  await page.clock.runFor(61_000);
  await card.locator('.review-dot').waitFor();
  await card.click();
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  check(await cycle.inputValue()==='test-minute','Reload lost test option');
  await cycle.selectOption('3');
  await page.getByRole('button',{name:'完成编辑',exact:true}).click();
  await page.getByRole('button',{name:'提交更新',exact:true}).click();
  await page.getByRole('button',{name:'回顾确认',exact:true}).waitFor();
  check((await record()).note.reviewTestMinute===false,'Could not return to monthly review');
  await page.clock.resume();
  return {cycle:'1 分钟（测试）',saved:true,due:'after 60 seconds',confirmed:'cleared; reminder recurs after another minute',monthly:'switch back succeeds'};
}
